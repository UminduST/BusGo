-- BusGo production-safe Supabase setup for the free tier.
-- Create driver users in Authentication > Users first, then assign their UUID below.
create table if not exists public.buses (
  id text primary key,
  driver_id uuid references auth.users(id),
  registration_no text not null,
  route_label text not null default 'Matugama to Aluthgama',
  lat double precision not null,
  lng double precision not null,
  speed numeric not null default 0,
  heading numeric not null default 0,
  status text not null default 'stopped',
  next_stop text default 'Route stop',
  eta text default '-',
  updated_at timestamptz not null default now()
);
alter table public.buses add column if not exists driver_id uuid references auth.users(id);
alter table public.buses enable row level security;

drop policy if exists "Public can read bus locations" on public.buses;
drop policy if exists "Drivers can update bus locations" on public.buses;
drop policy if exists "Drivers can update existing locations" on public.buses;
drop policy if exists "Authenticated drivers can insert assigned buses" on public.buses;
drop policy if exists "Drivers can update their assigned bus" on public.buses;

create policy "Public can read bus locations"
on public.buses for select
using (true);

create policy "Authenticated drivers can insert assigned buses"
on public.buses for insert to authenticated
with check (driver_id = (select auth.uid()));

create policy "Drivers can update their assigned bus"
on public.buses for update to authenticated
using (driver_id = (select auth.uid()))
with check (driver_id = (select auth.uid()));

do $$
begin
  if not exists (
    select 1
    from pg_publication_rel pr
    join pg_class c on c.oid = pr.prrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_publication p on p.oid = pr.prpubid
    where p.pubname = 'supabase_realtime'
      and n.nspname = 'public'
      and c.relname = 'buses'
  ) then
    alter publication supabase_realtime add table public.buses;
  end if;
end
$$;

