create table if not exists public.routes (
  id bigint generated by default as identity primary key,
  origin text not null,
  destination text not null,
  departure_time text not null,
  arrival_time text not null,
  duration text not null,
  available_seats integer not null default 0,
  price numeric not null default 0,
  created_at timestamptz not null default now()
);
alter table public.routes enable row level security;
drop policy if exists "Public can read routes" on public.routes;
create policy "Public can read routes" on public.routes for select using (true);

create table if not exists public.bookings (
  id text primary key,
  route_id bigint references public.routes(id),
  passenger_id uuid references auth.users(id),
  passenger_count integer not null default 1,
  seat_number text not null,
  status text not null default 'confirmed',
  created_at timestamptz not null default now()
);
alter table public.bookings enable row level security;
drop policy if exists "Passengers can read own bookings" on public.bookings;
drop policy if exists "Passengers can create own bookings" on public.bookings;
create policy "Passengers can read own bookings" on public.bookings for select to authenticated using (passenger_id = (select auth.uid()));
create policy "Passengers can create own bookings" on public.bookings for insert to authenticated with check (passenger_id = (select auth.uid()));
